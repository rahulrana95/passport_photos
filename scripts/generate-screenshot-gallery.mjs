/**
 * Builds a browsable index of every committed screenshot baseline.
 *
 * GitHub renders relative image paths inside a markdown file, so the generated
 * gallery is viewable directly in the repository — no artifact download, no CI
 * run needed to look at what a component currently looks like.
 *
 * Generated, never hand-edited: a hand-maintained gallery falls out of date the
 * first time someone is in a hurry.
 */
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

const SNAPSHOT_ROOT = resolve('e2e/visual/story-screenshots.spec.ts-snapshots');
const OUTPUT = resolve('e2e/visual/SCREENSHOTS.md');

/** "fail-desktop-dark-stories-linux.png" -> { story: "fail", variant: "desktop-dark" } */
const parseName = (fileName) => {
  const withoutSuffix = fileName.replace(/-stories-linux\.png$/, '');
  const match = /^(.*)-(desktop-light|desktop-dark|mobile-light)$/.exec(withoutSuffix);
  return match === null
    ? { story: withoutSuffix, variant: 'unknown' }
    : { story: match[1], variant: match[2] };
};

const titleCase = (slug) =>
  slug.split('-').map((word) => word.charAt(0).toUpperCase() + word.slice(1)).join(' ');

const componentDirs = readdirSync(SNAPSHOT_ROOT)
  .filter((entry) => statSync(join(SNAPSHOT_ROOT, entry)).isDirectory())
  .sort();

const lines = [
  '# Screenshot baselines',
  '',
  '> Generated by `npm run screenshots:gallery`. Do not edit by hand.',
  '',
  'Every story, in every theme and viewport, exactly as the visual regression',
  'suite compares it. Browsable here without downloading a CI artifact.',
  '',
  'A change to any of these images is a change a reviewer must approve:',
  '`npm run test:visual` fails on a single differing pixel.',
  '',
];

let total = 0;

for (const dir of componentDirs) {
  const files = readdirSync(join(SNAPSHOT_ROOT, dir)).filter((f) => f.endsWith('.png')).sort();
  if (files.length === 0) continue;

  lines.push(`## ${titleCase(dir)}`, '');

  const byStory = new Map();
  for (const file of files) {
    const { story, variant } = parseName(file);
    if (!byStory.has(story)) byStory.set(story, []);
    byStory.get(story).push({ variant, file });
  }

  for (const [story, variants] of byStory) {
    lines.push(`### ${titleCase(story)}`, '');
    for (const { variant, file } of variants.sort((a, b) => a.variant.localeCompare(b.variant))) {
      const path = relative(resolve('e2e/visual'), join(SNAPSHOT_ROOT, dir, file));
      lines.push(`**${variant}**`, '', `![${titleCase(story)} — ${variant}](./${path})`, '');
      total += 1;
    }
  }
}

lines.push('---', '', `${total} baselines across ${componentDirs.length} components.`, '');

writeFileSync(OUTPUT, lines.join('\n'), 'utf8');
console.log(`Wrote ${OUTPUT} — ${total} baselines, ${componentDirs.length} components.`);
